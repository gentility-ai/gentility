// Package gateway is the mothership's own node on the overlay: the one door
// every customer node reaches Gentility through.
//
// It runs the same binary a customer installs, as a platform-owned machine
// node, and it does two things. It terminates TLS on its overlay address in
// each organization with a leaf Gentility's internal CA issued, and it forwards
// each request as plain HTTP to the internal HTTP listener over the deploy's
// docker network — naming, in a signed header, the peer its own tsnet WhoIs
// attributed. The outbound lease API is implemented in lease.go.
//
// **The signature is the boundary.** The docker network, the bind address and
// a container's address are depth behind it: any of them can be true of
// something that is not the gateway. What the listener actually believes is
// that whoever set `X-Overlay-Peer` also held `OVERLAY_INGRESS_SECRET`, and
// the only reason that is worth believing about the ADDRESS is that this
// package deletes every client-supplied `X-Overlay-Peer*` header before it
// sets its own. Without that deletion a node would name any address it liked
// and the gateway would sign the lie.
//
// The wire format is written down in `contract/connector/capvers.md` under node_capver
// 1, and read on the other side by the signed-peer verifier.
// This package is written against that text; `sign_test.go` pins it against
// vectors generated by the server's signer, because two
// independent implementations of one MAC agreeing on prose is not the same as
// agreeing on bytes.
//
// Nothing here logs a secret, a derived key, a bearer or a private key. The
// refusals carry a status and the mothership's own one-word reason and nothing
// else, which is why they do not echo response bodies the way the node's other
// clients do.
package gateway

import (
	"crypto/hmac"
	"crypto/pbkdf2"
	"crypto/sha256"
	"encoding/base64"
	"fmt"
	"net/http"
	"strconv"
	"strings"

	"github.com/gentility-ai/gentility/connector/internal/enroll"
)

// The three headers the gateway sets on everything it forwards, and the whole
// of a node's identity before its own credential is checked.
//
// PeerHeader is enroll's constant rather than a second spelling of it: the
// direct dev hop names itself with the same header this signs, and one name
// written twice is one name that can be written differently.
const (
	PeerHeader    = enroll.PeerHeader
	PeerTsHeader  = "X-Overlay-Peer-Ts"
	PeerSigHeader = "X-Overlay-Peer-Sig"
)

// peerHeaderPrefix is what makes a header the client's to lose.
//
// A prefix rather than the three names above, and lowercased before the
// comparison, because this deletion is the reason the listener may believe the
// header at all. A fourth `X-Overlay-Peer-…` invented in a later capver must
// not be arrivable from outside merely because this list was written before it
// existed.
const peerHeaderPrefix = "x-overlay-peer"

// The internal bearer's key derivation is PBKDF2-HMAC-SHA256 with 1000
// iterations and a 32-octet result. The salt is also the domain separation: the peer
// signature MACs `<peer>:<ts>` with the raw secret and the bearer MACs
// `gateway:<ts>` with a key derived from it, so neither protocol's messages
// are replayable as the other's.
const (
	bearerSalt       = "overlay internal bearer v1"
	bearerIterations = 1000
	bearerKeyLength  = 32
)

// bearerSubject is the only subject the internal bearer format accepts.
const bearerSubject = "gateway"

// Sign is the peer signature, byte for byte (contract/connector/capvers.md, node_capver 1):
//
//	message = <X-Overlay-Peer verbatim> ++ ":" ++ <X-Overlay-Peer-Ts verbatim>
//	sig     = base64.RawURLEncoding(HMAC-SHA256(key = OVERLAY_INGRESS_SECRET, message))
//
// One ASCII colon and nothing else — no length prefix, no newline, no header
// names. RawURLEncoding because the app decodes with
// `Base.url_decode64(padding: false)` and has no fallback: a padded or
// standard-alphabet encoding is refused as `bad_signature`.
//
// The timestamp is spelled by strconv.FormatInt, which is the canonical
// decimal the contract asks for — ASCII digits, no sign, no leading zero — and
// the same bytes go into the message and into the header. Formatting it twice
// would be two chances to spell one integer two ways.
func Sign(secret []byte, peer string, unixTs int64) string {
	mac := hmac.New(sha256.New, secret)
	mac.Write([]byte(peer + ":" + strconv.FormatInt(unixTs, 10)))

	return base64.RawURLEncoding.EncodeToString(mac.Sum(nil))
}

// Bearer is the token that fetches the gateway's own TLS leaf, in
// the internal bearer format: two unpadded url-safe base64
// halves joined by a dot, the first the payload `gateway:<unix ts>` and the
// second its MAC under the derived key.
//
// It is minted per fetch. The app accepts it for a minute either side of the
// second named — symmetric, because the app and the gateway are two containers
// with two clocks and a gateway running a second fast is not an attacker.
func Bearer(secret []byte, unixTs int64) (string, error) {
	key, err := pbkdf2.Key(sha256.New, string(secret), []byte(bearerSalt), bearerIterations, bearerKeyLength)
	if err != nil {
		return "", fmt.Errorf("gateway: deriving the internal bearer key: %w", err)
	}

	payload := bearerSubject + ":" + strconv.FormatInt(unixTs, 10)
	mac := hmac.New(sha256.New, key)
	mac.Write([]byte(payload))

	return base64.RawURLEncoding.EncodeToString([]byte(payload)) +
		"." + base64.RawURLEncoding.EncodeToString(mac.Sum(nil)), nil
}

// stripPeerHeaders deletes every X-Overlay-Peer* header the client supplied.
//
// It ranges the map rather than calling Del three times: Go canonicalises
// header names as it parses them, so the three names would cover every request
// that arrived over HTTP — but "would cover" is not the property this needs to
// have. Deleting by prefix is the same cost and does not depend on a
// canonicalisation staying true.
//
// Deleting from a map while ranging it is defined behaviour in Go: an entry
// removed before it is reached is not produced.
func stripPeerHeaders(header http.Header) {
	for name := range header {
		if strings.HasPrefix(strings.ToLower(name), peerHeaderPrefix) {
			delete(header, name)
		}
	}
}
